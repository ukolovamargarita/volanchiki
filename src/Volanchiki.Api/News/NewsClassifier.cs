namespace Volanchiki.Api.News;

/// <summary>Грубая рубрика по ключевым словам — блок «парсер → классификация» из кейса.</summary>
public static class NewsClassifier
{
    static readonly (string Tag, string[] Keys)[] Rules =
    {
        ("Ставка", new[] { "ключев", "ставк", "цб ", "банк россии", "регулятор", "процентн" }),
        ("Инфляция", new[] { "инфляц", "росстат", "потребительск цен", "ипц" }),
        ("Макро", new[] { "ввп", "макро", "безработиц", "рынок труда", "промышленн", "пмэм" }),
        ("Валюта", new[] { "доллар", "евро", "курс", "рубл", "валют", "юань" }),
        ("Нефть", new[] { "нефть", "brent", "urals", "газпром", "газ ", "спг" }),
        ("Металлы", new[] { "сталь", "металл", "золото", "алюмин", "никел", "медь" }),
        ("Финансы", new[] { "облигац", "акци", "биржа", "мосбирж", "кредит", "депозит", "банк" }),
        ("Санкции", new[] { "санкц", "ограничен", "экспортн контроль" }),
        ("Регион", new[] { "область", "край", "республик", "губернатор" }),
    };

    public static string Classify(string title, string summary)
    {
        var hay = (title + " " + summary).ToLowerInvariant();
        foreach (var (tag, keys) in Rules)
        {
            foreach (var k in keys)
            {
                if (hay.Contains(k))
                    return tag;
            }
        }

        return "Прочее";
    }
}
